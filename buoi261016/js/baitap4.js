let currentLanguage = "vi";
const menuToggle = document.getElementById("menuToggle");
const primaryNav = document.getElementById("primaryNav");
const bagButton = document.getElementById("bagButton");
const bagCount = document.getElementById("bagCount");
const languageToggle = document.getElementById("languageToggle");
const toast = document.getElementById("toast");
const newsletterStatus = document.getElementById("newsletterStatus");
const cart = [];
let toastTimer;
let activeToast = null;
let newsletterSubmitted = false;

function localizedMessage(key, values = {}) {
  return Object.entries(values).reduce(
    (message, [name, value]) => {
      const localizedValue = name === "price" && typeof value === "number" ? formatPrice(value) : value;
      return message.replaceAll(`{${name}}`, localizedValue);
    },
    translations[currentLanguage][key]
  );
}

function applyLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];
  document.documentElement.lang = language;
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]').content = dictionary.pageDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = dictionary[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = dictionary[element.dataset.i18nHtml];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", dictionary[element.dataset.i18nAriaLabel]);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = dictionary[element.dataset.i18nAlt];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = dictionary[element.dataset.i18nPlaceholder];
  });
  document.querySelectorAll("[data-price-display]").forEach((element) => {
    element.textContent = formatPrice(Number(element.dataset.priceDisplay));
  });

  const menuIsOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-label", menuIsOpen ? dictionary.menuClose : dictionary.menuOpen);
  languageToggle.textContent = language === "vi" ? "EN" : "VI";
  languageToggle.setAttribute("aria-label", dictionary.switchLanguage);
  languageToggle.title = dictionary.switchLanguage;
  bagButton.setAttribute("aria-label", getCartLabel());
  if (newsletterSubmitted) {
    newsletterStatus.textContent = dictionary.newsletterSuccess;
  }
  if (activeToast && toast.classList.contains("is-visible")) {
    toast.textContent = localizedMessage(activeToast.key, activeToast.values);
  }
}

languageToggle.addEventListener("click", () => {
  applyLanguage(currentLanguage === "vi" ? "en" : "vi");
});

function closeMenu() {
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", translations[currentLanguage].menuOpen);
  primaryNav.classList.remove("is-open");
  document.body.classList.remove("menu-open");
}

menuToggle.addEventListener("click", () => {
  const isOpen = menuToggle.getAttribute("aria-expanded") !== "true";
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? translations[currentLanguage].menuClose : translations[currentLanguage].menuOpen);
  primaryNav.classList.toggle("is-open", isOpen);
  document.body.classList.toggle("menu-open", isOpen);
});

primaryNav.addEventListener("click", (event) => {
  if (event.target.closest("a")) closeMenu();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

function showToast(message) {
  const { key, values } = message;
  activeToast = { key, values };
  toast.textContent = localizedMessage(key, values);
  toast.classList.add("is-visible");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => {
    toast.classList.remove("is-visible");
    activeToast = null;
  }, 2800);
}

function getCartLabel() {
  const count = bagCount.textContent;
  const key = currentLanguage === "en" && Number(count) === 1 ? "cartLabelOne" : "cartLabel";
  return localizedMessage(key, { count });
}

function formatPrice(price) {
  const locale = currentLanguage === "vi" ? "vi-VN" : "en-US";
  const formatted = new Intl.NumberFormat(locale).format(price);
  return currentLanguage === "vi" ? `${formatted}₫` : `₫${formatted}`;
}

document.querySelectorAll("[data-add-product]").forEach((button) => {
  button.addEventListener("click", () => {
    const { addProduct, price } = button.dataset;
    cart.push({ name: addProduct, price: Number(price) });
    bagCount.textContent = String(cart.length);
    bagButton.setAttribute("aria-label", getCartLabel());
    showToast({ key: "addedToCart", values: { product: addProduct, price: Number(price) } });
  });
});

bagButton.addEventListener("click", () => {
  if (cart.length === 0) {
    showToast({ key: "emptyCart", values: {} });
    return;
  }

  const total = cart.reduce((sum, item) => sum + item.price, 0);
  const productNames = [...new Set(cart.map((item) => item.name))].join(", ");
  const summaryKey = currentLanguage === "en" && cart.length === 1 ? "cartSummaryOne" : "cartSummary";
  showToast({
    key: summaryKey,
    values: { count: cart.length, products: productNames, price: total }
  });
});

const tabs = [...document.querySelectorAll(".spec-tab")];
const panels = [...document.querySelectorAll(".spec-panel")];

function activateTab(tab, moveFocus = false) {
  const targetPanelId = tab.getAttribute("aria-controls");

  tabs.forEach((item) => {
    const isActive = item === tab;
    item.classList.toggle("is-active", isActive);
    item.setAttribute("aria-selected", String(isActive));
    item.tabIndex = isActive ? 0 : -1;
  });

  panels.forEach((panel) => {
    panel.hidden = panel.id !== targetPanelId;
    panel.classList.toggle("is-active", panel.id === targetPanelId);
  });

  if (moveFocus) tab.focus();
}

tabs.forEach((tab, index) => {
  tab.addEventListener("click", () => activateTab(tab));
  tab.addEventListener("keydown", (event) => {
    let nextIndex = index;
    if (event.key === "ArrowRight") nextIndex = (index + 1) % tabs.length;
    else if (event.key === "ArrowLeft") nextIndex = (index - 1 + tabs.length) % tabs.length;
    else if (event.key === "Home") nextIndex = 0;
    else if (event.key === "End") nextIndex = tabs.length - 1;
    else return;

    event.preventDefault();
    activateTab(tabs[nextIndex], true);
  });
});

const revealElements = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}

document.getElementById("newsletterForm").addEventListener("submit", (event) => {
  event.preventDefault();
  newsletterSubmitted = true;
  newsletterStatus.textContent = translations[currentLanguage].newsletterSuccess;
  event.currentTarget.reset();
});

applyLanguage(currentLanguage);
